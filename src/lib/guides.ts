export function isPublished(g: Guide): boolean {
  return Array.isArray(g.body) && g.body.length > 0;
}

export function publishedGuides(): Guide[] {
  return GUIDES.filter(isPublished);
}

export function getGuide(slug: string): Guide | undefined {
  const g = GUIDES.find((x) => x.slug === slug);
  return g && isPublished(g) ? g : undefined;
}

export function siblingGuides(current: Guide, limit = 3): Guide[] {
  return publishedGuides()
    .filter((g) => g.slug !== current.slug && g.cluster === current.cluster)
    .slice(0, limit);
}

export function guidesByCluster(cluster: GuideCluster): Guide[] {
  return publishedGuides().filter((g) => g.cluster === cluster);
}
