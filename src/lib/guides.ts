export type GuideCluster = "health" | "premium" | "car" | "hub";

export type GuideBlock = {
  h2: string;
  // 문단/리스트 내 **굵게** 표기는 상세 페이지에서 <strong>으로 렌더링됩니다.
  p?: string[];
  ul?: string[];
};

export type GuideFAQ = { q: string; a: string };

/** 독자가 직접 확인할 수 있는 공식 자료. 계산 엔진의 RegulatorySource 와 같은 성격이다. */
export type GuideSource = {
  title: string; // 문서 이름(연혁본·발령일 포함)
  issuer: string; // 발행 기관
  url: string; // 공식 주소
  locator?: string; // 조문·표·쪽 등 위치
  checkedAt: string; // 이 글의 주장과 대조한 날 (YYYY-MM-DD)
};

/**
 * 검수 상태. 본문이 있다는 사실은 검수와 무관하다.
 *   verified — 글의 수치·법규 주장을 모두 공식 자료와 대조했다.
 *   partial  — 일부만 대조했다. unchecked 에 대조하지 않은 범위와 이유를 적는다.
 *   pending  — 아직 대조하지 않았다. unchecked 에 이유를 적는다. 상세 페이지에 대기 안내가 표시된다.
 * publishedGuides() 가 이 규칙을 빌드 시점에 강제한다(assertGuideReview).
 */
export type GuideReviewStatus = "verified" | "partial" | "pending";
export type GuideReview = {
  status: GuideReviewStatus;
  checkedAt?: string; // verified·partial 필수
  scope?: string; // 대조한 범위 (verified·partial 필수)
  unchecked?: string; // 대조하지 않은 범위와 이유 (partial·pending 필수)
};

export type Guide = {
  slug: string;
  cluster: GuideCluster;
  title: string; // H1 / 목록 제목
  seoTitle?: string; // <title> (없으면 title 사용)
  description: string; // meta description
  keyword: string; // 타깃 키워드
  intro: string; // H1 하단 도입부
  updated: string; // YYYY-MM-DD — 본문을 고친 날. 검수만 했을 때는 바꾸지 않는다(review.checkedAt 에 기록).
  review: GuideReview; // 검수 상태 (필수)
  sources?: GuideSource[]; // 참고한 공식 자료
  body?: GuideBlock[]; // 비어 있으면 초안(미발행)
  faqs?: GuideFAQ[];
};

