// #13 비급여 보험료 할인·할증 — HOLD.
//
// ⚠ 이 항목만 성격이 다르다. **보험금이 아니라 보험료** 산출 영역이다.
//
// 감독규정은 확정·시행 중이고 원문도 확인됐다.
//   보험업감독규정 [시행 2026. 5. 6.] 제7-63조② 3의2·3의3, 제7-73조⑨
//   규칙 GEN2026-NON-BENEFIT-PREMIUM-ADJUSTMENT에 출처를 등록해 두었다.
//
// 막힌 이유는 **공통 규정에 상품별 계산 수치가 없다**는 것이다.
// 감독규정이 정하는 것은 적용 대상(비중증비급여 특약 순보험료 총액), 산정기간
// (갱신 전 12개월), 제외 계약군, 그리고 "적용할 수 있을 것"이라는 임의규정과
// 상대도 적용 전·후 총보험료 수준을 맞춘다는 원칙뿐이다.
// 등급 경계·할인율·할증률·제외 보험금·반올림·적용 순서는 회사가 정한다.
//
// 금융위 2024.6.7. 보도자료의 5구간과 예상 할인율은 **4세대 제도** 설명이며
// 감독규정 조문에 없다. 5세대 고정 상수로 전용하지 않는다.
//
// 해제 조건: 해당 상품·보험사의 공식 요율표 또는 약관에서
//   등급 경계 / 할인·할증률 / 제외 보험금 / 반올림·적용 순서가 확인될 것.
// 설계 판단: 구현하더라도 보험금 청구 엔진이 아니라 별도 보험료 도메인으로 분리한다.
//   1등급 할인율은 회사별로 다르므로 반드시 파라미터화하고 하드코딩하지 않는다.
export const DISCOUNT_STATUS = "HOLD" as const;
export function applyDiscount(): never {
  throw new Error(
    "[HOLD] 비급여 보험료 할인·할증 미구현: 감독규정 근거는 확인됨(보험업감독규정 제7-63조②3의3·제7-73조⑨). " +
    "공통 규정에 등급 경계·요율·반올림 산식이 없어 상품·보험사별 요율표 확보 전까지 공통 계산 불가. " +
    "보험금이 아니라 보험료 영역이므로 별도 도메인으로 분리 대상(#13)",
  );
}
