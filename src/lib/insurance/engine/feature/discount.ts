// #13 비급여 보험료 할인·할증 — HOLD.
//
// ⚠ 이 항목만 성격이 다르다. **보험금이 아니라 보험료** 산출 영역이다.
//
// 근거는 대부분 확정됐다(2026-09-03 약관 직독). 확정된 것은 규칙으로 등록돼 있다.
//   GEN2026-PREMIUM-ADJ-LOOKBACK             산정기간(갱신 3개월 전 말일부터 직전 12개월)
//   GEN2026-PREMIUM-ADJ-BASE                 적용 대상(특별약관2 순보험료 총액)
//   GEN2026-PREMIUM-ADJ-EXCLUDED-CLAIMS      장기요양 1·2등급 판정자 비급여의료비 제외
//   GEN2026-PREMIUM-ADJ-TIERS                5단계 구간 경계와 요율 상대도(2~5단계 100/200/300/400%)
//   GEN2026-PREMIUM-ADJ-SURCHARGE-THRESHOLD  할증은 연간 지급실적 100만원 이상 계약만
//   근거: 별표15 특별약관2 제6조③④ (5.6본·7.15 시행본 p.310, 8.28본 p.311)
//        보험업감독규정 제7-63조② 3의2·3의3, 제7-73조⑨
//
// 그럼에도 스텁이 HOLD인 이유는 둘이고, 성격이 다르다.
//
//   (1) 1단계 할인율이 공통 고정값일 수 없다.
//       약관은 값이 아니라 산출 원칙만 정한다 — 매년 3~5단계 할증재원을 1단계
//       대상자에게 분배해 산출한다(제6조③ 주, 제6조④). 해마다, 회사마다 달라진다.
//       약관의 보험료 예시표도 "1단계(요율상대도 95% 가정)"이라고 가정임을 밝힌다.
//
//   (2) 보험금 엔진이 아니라 별도 보험료 도메인이 필요하다.
//       입력(지급실적·특별약관2 순보험료)도 출력(보험료)도 CalcResult와 무관하다.
//       최종 보험료를 내려면 상품별 반올림과 다른 할인과의 적용 순서도 필요하다.
//
// 해제 조건: 해당 상품·보험사의 공식 요율표 또는 약관에서 그 해의 1단계 할인율과
//           반올림·적용 순서가 확인될 것. 그리고 보험료 도메인을 별도로 둘 것.
export const DISCOUNT_STATUS = "HOLD" as const;
export function applyDiscount(): never {
  throw new Error(
    "[HOLD] 비급여 보험료 할인·할증 미구현: 산정기간·구간 경계·할증률(2~5단계) 근거는 확인됨" +
    "(별표15 특별약관2 제6조③④, 보험업감독규정 제7-63조②3의3). " +
    "1단계 할인율은 매년 할증재원 배분으로 산출되어 공통 고정값이 아니고, " +
    "보험금이 아니라 보험료 영역이라 별도 도메인과 순보험료 입력이 필요함(#13)",
  );
}
